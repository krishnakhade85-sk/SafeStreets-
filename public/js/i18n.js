let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('safestreets_lang')) || 'en';
if (!I18N_STRINGS[currentLang]) currentLang = 'en';

function setLanguage(lang) {
  if (I18N_STRINGS[lang]) {
    currentLang = lang;
    try {
      localStorage.setItem('safestreets_lang', lang);
    } catch (e) {}
    document.documentElement.setAttribute('lang', lang);
    const select = document.getElementById('app-lang-select');
    if (select && select.value !== lang) {
      select.value = lang;
    }
    applyTranslations();
  }
}

function t(key) {
  return (I18N_STRINGS[currentLang] && I18N_STRINGS[currentLang][key]) || 
         (I18N_STRINGS.en && I18N_STRINGS.en[key]) || 
         key;
}

function applyTranslations() {
  document.documentElement.setAttribute('lang', currentLang);
  const select = document.getElementById('app-lang-select');
  if (select && select.value !== currentLang) {
    select.value = currentLang;
  }

  document.querySelectorAll('[data-i18n]').forEach(elem => {
    const key = elem.getAttribute('data-i18n');
    const translation = t(key);
    if (elem.tagName === 'INPUT' && elem.hasAttribute('placeholder')) {
      elem.placeholder = translation;
    } else {
      elem.textContent = translation;
    }
  });
}

window.SafeStreetsI18n = {
  setLanguage,
  t,
  applyTranslations,
  getCurrentLang: () => currentLang
};
